//! 流类型标签(V3-5 Stage B 多路复用)。
//!
//! 暖连接(入池的 mux 直连)上,每条双向流以一个类型标签字节开头,
//! 接收端据此把流分派给对应服务:[`TAG_CTRL`] → ctrl 请求-响应,
//! [`TAG_TRANSFER`] → 传输引擎控制流。数据面 `open_uni` 块流不标签、
//! 帧格式不动(传输独占,spec §3.2)。裸路径(每作业新拨连接、中继
//! 连接、旧端互通)一律不写标签——标签只在协商出 mux 的入池直连上
//! 使用,字节值在此单一真源。

/// ctrl 请求-响应流标签。
pub const TAG_CTRL: u8 = 0x01;

/// 传输引擎控制流标签。
pub const TAG_TRANSFER: u8 = 0x02;
